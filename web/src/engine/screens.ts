export function words(lang: Lang): Words {
  return lang === 'am' ? am : en;
}

export function langOf(el: Element): Lang {
  return el.getAttribute('lang') === 'am' ? 'am' : 'en';
}

/** A date in the learner's language, without the time of day (calmer to read aloud). */
export function day(iso: string, lang: Lang): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  try {
    return d.toLocaleDateString(lang === 'am' ? 'am-ET' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
  } catch {
    return d.toISOString().slice(0, 10);
  }
}
