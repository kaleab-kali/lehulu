//! Lehulu server: REST API (/v1), OpenAPI docs (/docs) and the built web component, in one binary.
//! Commands: `lehulu serve` (default), `lehulu healthcheck` (used by Docker), `lehulu seed`,
//! `lehulu create-client partner|employer <id> [name]`, `lehulu backup <file>`, `lehulu openapi [file]`.

mod adapters;
mod auth;
mod config;
mod db;
mod domain;
mod error;
mod openapi;
mod routes;
mod webhook;

use std::{
    io::{Read, Write},
    net::TcpStream,
    time::Duration,
};

#[tokio::main]
async fn main() {
    let cmd = std::env::args().nth(1).unwrap_or_else(|| "serve".into());
    match cmd.as_str() {
        "serve" => serve().await,
        "healthcheck" => std::process::exit(healthcheck()),
        "seed" => {
            let cfg = config::Config::from_env();
            let pool = db::connect(&cfg)
                .await
                .expect("Could not open the database");
            db::seed(&pool, &cfg).await.expect("Seeding failed");
            println!("Seed data loaded.");
        }
        "create-client" => {
            let args: Vec<String> = std::env::args().skip(2).collect();
            let (Some(kind), Some(id)) = (args.first(), args.get(1)) else {
                eprintln!("Use: lehulu create-client partner|employer <id> [display name]");
                std::process::exit(2);
            };
            let cfg = config::Config::from_env();
            let pool = db::connect(&cfg)
                .await
                .expect("Could not open the database");
            match db::create_client(&pool, kind, id, args.get(2).map(String::as_str)).await {
                Ok(secret) => println!(
                    "Organisation ID (client ID): {id}
Password (client secret): {secret}
Give these to the {kind} privately. The secret is shown only now."
                ),
                Err(e) => {
                    eprintln!("Could not create the client: {e}");
                    std::process::exit(1);
                }
            }
        }
        "openapi" => {
            // JSON is valid YAML, so this writes openapi.yaml without a YAML library.
            use utoipa::OpenApi;
            let doc = openapi::ApiDoc::openapi()
                .to_pretty_json()
                .expect("OpenAPI document");
            match std::env::args().nth(2) {
                Some(file) => {
                    std::fs::write(
                        &file,
                        format!(
                            "# Generated by `lehulu openapi {file}`. Do not edit by hand.\n{doc}\n"
                        ),
                    )
                    .expect("Could not write the file");
                    println!("OpenAPI document written to {file}.");
                }
                None => println!("{doc}"),
            }
        }
        "backup" => {
            let Some(file) = std::env::args().nth(2) else {
                eprintln!("Use: lehulu backup <file>   (for example data/backup-2026-11-15.db)");
                std::process::exit(2);
            };
            let cfg = config::Config::from_env();
            let pool = db::connect(&cfg)
                .await
                .expect("Could not open the database");
            db::backup(&pool, &file).await.expect("Backup failed");
            println!(
                "Backup written to {file}. Recordings are in MEDIA_DIR; copy that folder too."
            );
        }
        other => {
            eprintln!("Unknown command `{other}`. Use: serve | healthcheck | seed | create-client | backup | openapi [file]");
            std::process::exit(2);
        }
    }
}

async fn serve() {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "info,tower_http=info".into()),
        )
        .init();
    let cfg = config::Config::from_env();
    let pool = db::connect(&cfg)
        .await
        .expect("Could not open the SQLite database. Check DATABASE_URL.");
    db::seed_if_empty(&pool, &cfg)
        .await
        .expect("Seeding failed");
    if cfg.demo_mode {
        tracing::warn!("DEMO_MODE is on: demo sign-ins (<id> / <id>-demo), codes shown on screen and /dev/sms. Turn it off in production.");
    } else if cfg.sms_adapter == "simulator" {
        tracing::warn!("SMS_ADAPTER=simulator and DEMO_MODE is off: no text messages leave this server, so learners cannot get sign-in codes. Connect an SMS gateway (src/adapters/sms.rs).");
    }
    if cfg.allowed_origins.is_empty() {
        tracing::info!("ALLOWED_ORIGINS is empty: only pages served by this server can call the API. Add your platform's origin to embed Lehulu elsewhere.");
    }
    let state = routes::AppState::new(pool, cfg.clone());
    // Privacy policy (F21): delete what we no longer need, at start and every 6 hours.
    let retention_state = state.clone();
    tokio::spawn(async move {
        let mut tick = tokio::time::interval(Duration::from_secs(6 * 3600));
        loop {
            tick.tick().await;
            match routes::learners::retention(&retention_state).await {
                Ok(n) if n > 0 => tracing::info!("retention: deleted {n} inactive accounts"),
                Ok(_) => {}
                Err(e) => tracing::warn!(error = %e, "retention job failed"),
            }
        }
    });
    let app = routes::router(state);
    let listener = tokio::net::TcpListener::bind(&cfg.bind)
        .await
        .unwrap_or_else(|e| panic!("Could not listen on {}: {e}", cfg.bind));
    tracing::info!(
        "Lehulu is running on http://{}  (API docs: /docs)",
        cfg.bind
    );
    axum::serve(listener, app)
        .with_graceful_shutdown(shutdown_signal())
        .await
        .expect("Server error");
}

async fn shutdown_signal() {
    let ctrl_c = async {
        let _ = tokio::signal::ctrl_c().await;
    };
    #[cfg(unix)]
    let terminate = async {
        if let Ok(mut s) = tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())
        {
            s.recv().await;
        }
    };
    #[cfg(not(unix))]
    let terminate = std::future::pending::<()>();
    tokio::select! { _ = ctrl_c => {}, _ = terminate => {} }
}

/// Tiny HTTP check without extra dependencies. Exit code 0 = healthy.
fn healthcheck() -> i32 {
    let cfg = config::Config::from_env();
    let port = cfg.bind.rsplit(':').next().unwrap_or("8080");
    let addr = format!("127.0.0.1:{port}");
    let Ok(addr) = addr.parse() else {
        return 1;
    };
    let Ok(mut stream) = TcpStream::connect_timeout(&addr, Duration::from_secs(2)) else {
        return 1;
    };
    let _ = stream.set_read_timeout(Some(Duration::from_secs(2)));
    if stream
        .write_all(b"GET /healthz HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n")
        .is_err()
    {
        return 1;
    }
    let mut buf = [0u8; 64];
    match stream.read(&mut buf) {
        Ok(n) if String::from_utf8_lossy(&buf[..n]).contains(" 200 ") => 0,
        _ => 1,
    }
}
